-- Meridian Healthcare Cost
-- Milestone 4: SQLite to PostgreSQL migration
-- Original tables: jobs, patients

CREATE TABLE jobs (
    id VARCHAR NOT NULL,
    status VARCHAR,
    filename VARCHAR,
    total_records INTEGER,
    processed_records INTEGER,
    high_risk_found INTEGER,
    error_message VARCHAR,
    created_at TIMESTAMP,
    completed_at TIMESTAMP,
    PRIMARY KEY (id)
);

CREATE INDEX ix_jobs_id
ON jobs (id);

CREATE TABLE patients (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source VARCHAR,
    age INTEGER,
    sex INTEGER,
    chronic_condition_count INTEGER,
    prior_inpatient_visits INTEGER,
    prior_outpatient_visits INTEGER,
    prior_reimbursement DOUBLE PRECISION,
    predicted_cost DOUBLE PRECISION,
    risk_level VARCHAR,
    percentile INTEGER,
    created_at TIMESTAMP
);

CREATE INDEX ix_patients_id
ON patients (id);
